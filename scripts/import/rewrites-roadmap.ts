import { splitCells } from './roadmap-parser';

/** §9.2: drops the Date cell and replaces the reserved problems with what a learner may know beforehand. */
const assessmentRow = (line: number, unseen: string): LineEdit =>
  T(
    line,
    (text) => {
      const [id, , topics, cold, , total, pass] = splitCells(text);
      return `| ${id} | ${topics} | ${cold} | ${unseen} | ${total} | ${pass} |`;
    },
    'reserved-cell',
  );

/** §2: a week row without its dates. */
const overviewRow = (line: number, dates: string, module: number): LineEdit =>
  E(line, `| ${module} (${dates}) |`, `| ${module} |`, 'calendar-date');

/** §7.2: the "Where taught" column used schedule codes. */
const whereTaught = (line: number, from: string, to: string): LineEdit =>
  E(line, `| ${from} |`, `| ${to} |`, 'rename-week');

